if [[ ! -f "${RUN_SCRIPT}" ]]; then
    echo "Run script not found: ${RUN_SCRIPT}" >&2
    exit 1
fi
if (( RJOB_GPU != NUM_GPUS )); then
    echo "Invalid RJOB_GPU=${RJOB_GPU}; keep RJOB_GPU equal to NUM_GPUS(${NUM_GPUS})." >&2
    exit 1
fi

case "${RJOB_PRIVATE_MACHINE,,}" in
