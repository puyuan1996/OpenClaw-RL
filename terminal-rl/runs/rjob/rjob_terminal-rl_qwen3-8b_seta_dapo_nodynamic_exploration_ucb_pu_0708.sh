#!/bin/bash

################################################################################
# Submit OpenClaw terminal-rl Qwen3-8B SETA exploration as an rjob.
#
# Variant A: v0710 K6 quality-balanced.
#
# This is the conservative "best next" variant after the previous v0629/v0707
# experiments:
#   - keep turn-position novelty off, because epturn=bucket increased late
#     truncation in the v0629_3 epturn run;
#   - use UCB value=quality_gate, so arm ranking penalizes parse errors and
#     low-outcome truncation instead of ranking by raw normalized outcome only;
#   - use K=6 with N_SAMPLES=8, giving UCB room to repeat promising arms while
#     preserving more arm diversity than the aggressive K4 exploit variant;
#   - keep advantage lambda lower than v0707's 0.08 to reduce early reward
#     shaping noise while still making intrinsic advantage visible.
#
# GPU profiles:
#   NUM_GPUS=4 -> actor=2, rollout=2, TP=2, cpu=80,  mem=800000
#   NUM_GPUS=8 -> actor=4, rollout=4, TP=4, cpu=150, mem=1500000
# Scheduler group defaults to rlinfra_gpu regardless of NUM_GPUS; override with
# RJOB_CHARGED_GROUP=... when needed.
################################################################################

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OPENCLAW_HOME="${OPENCLAW_HOME:-$(cd "${SCRIPT_DIR}/../../.." && pwd)}"

RUN_TIMESTAMP="${RUN_TIMESTAMP:-$(date '+%Y-%m-%d_%H%M%S')}"
NUM_GPUS="${NUM_GPUS:-4}"
NUM_ROLLOUT="${NUM_ROLLOUT:-10000}"

case "${NUM_GPUS}" in
    4)
        DEFAULT_ACTOR_GPUS=2
        DEFAULT_ROLLOUT_GPUS=2
        DEFAULT_RJOB_CPU=80
        DEFAULT_RJOB_MEMORY=800000
        ;;
    8)
        DEFAULT_ACTOR_GPUS=4
        DEFAULT_ROLLOUT_GPUS=4
        DEFAULT_RJOB_CPU=150
        DEFAULT_RJOB_MEMORY=1500000
        ;;
    *)
        echo "Invalid NUM_GPUS=${NUM_GPUS}; use NUM_GPUS=4 or NUM_GPUS=8." >&2
        exit 1
        ;;
esac

DEFAULT_RJOB_CHARGED_GROUP="rlinfra_gpu"

ACTOR_GPUS="${ACTOR_GPUS:-${DEFAULT_ACTOR_GPUS}}"
ROLLOUT_GPUS="${ROLLOUT_GPUS:-${DEFAULT_ROLLOUT_GPUS}}"
ROLLOUT_NUM_GPUS_PER_ENGINE="${ROLLOUT_NUM_GPUS_PER_ENGINE:-${ROLLOUT_GPUS}}"
TP_SIZE="${TP_SIZE:-${ACTOR_GPUS}}"
ROLLOUT_BATCH_SIZE="${ROLLOUT_BATCH_SIZE:-8}"
N_SAMPLES="${N_SAMPLES:-8}"
MAX_TOKENS_PER_GPU="${MAX_TOKENS_PER_GPU:-16384}"
