    echo "Invalid ROLLOUT_NUM_GPUS_PER_ENGINE=${ROLLOUT_NUM_GPUS_PER_ENGINE}; it must be <= ROLLOUT_GPUS(${ROLLOUT_GPUS})." >&2
    exit 1
fi
