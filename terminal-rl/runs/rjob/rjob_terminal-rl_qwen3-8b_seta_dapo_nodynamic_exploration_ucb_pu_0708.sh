ROLLOUT_MAX_CONTEXT_LEN="${ROLLOUT_MAX_CONTEXT_LEN:-16384}"
DEFAULT_WORKER_URLS_FILE="${OPENCLAW_HOME}/terminal-rl/worker_urls.txt"
if [[ -n "${SERVER_IP_FILE:-}" && -n "${WORKER_URLS_FILE:-}" && "${SERVER_IP_FILE}" != "${WORKER_URLS_FILE}" ]]; then
    echo "Conflicting SERVER_IP_FILE=${SERVER_IP_FILE} and WORKER_URLS_FILE=${WORKER_URLS_FILE}; set only one." >&2
    exit 1
fi
