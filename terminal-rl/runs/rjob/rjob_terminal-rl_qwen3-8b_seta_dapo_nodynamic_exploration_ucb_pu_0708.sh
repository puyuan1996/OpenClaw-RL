EXPLORE_TRUNCATION_PENALTY_OUTCOME_AWARE="${EXPLORE_TRUNCATION_PENALTY_OUTCOME_AWARE:-1}"

SLIME_SKIP_ZERO_TRAINABLE_ROLLOUT="${SLIME_SKIP_ZERO_TRAINABLE_ROLLOUT:-1}"
SLIME_SKIP_ZERO_TRAINABLE_TRAIN="${SLIME_SKIP_ZERO_TRAINABLE_TRAIN:-1}"

