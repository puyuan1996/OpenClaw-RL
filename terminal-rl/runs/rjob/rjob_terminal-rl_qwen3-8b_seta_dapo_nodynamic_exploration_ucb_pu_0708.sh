    echo "Invalid GPU split: ACTOR_GPUS(${ACTOR_GPUS}) + ROLLOUT_GPUS(${ROLLOUT_GPUS}) > NUM_GPUS(${NUM_GPUS})." >&2
    exit 1
fi
if (( ACTOR_GPUS < 1 || ROLLOUT_GPUS < 1 )); then
    echo "Invalid GPU split: ACTOR_GPUS=${ACTOR_GPUS}, ROLLOUT_GPUS=${ROLLOUT_GPUS}; both must be >= 1." >&2
    exit 1
fi
