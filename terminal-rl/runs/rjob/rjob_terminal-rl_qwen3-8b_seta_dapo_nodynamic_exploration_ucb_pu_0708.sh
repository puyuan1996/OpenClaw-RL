VARIANT_ID="${VARIANT_ID:-v0710_k6_quality_balanced1000}"
RUN_ID="${RUN_ID:-terminal-rl_qwen3-8b_${NUM_GPUS}gpu_seta_dapo_nodynamic_exploration_simhash_life_fp_ucb_${VARIANT_ID}_${EPISODIC_TURN_TAG}_dualadv_think_${RUN_TIMESTAMP}}"
RUN_NAME="${RUN_NAME:-${RUN_ID}}"
RUNS_ROOT="${RUNS_ROOT:-${OPENCLAW_HOME}/runs}"
MAX_CKPT_KEEP="${MAX_CKPT_KEEP:-3}"
SAVE_INTERVAL="${SAVE_INTERVAL:-100}"
WANDB_MODE="${WANDB_MODE:-offline}"
WANDB_ENABLE="${WANDB_ENABLE:-1}"
WANDB_DIR="${WANDB_DIR:-${RUNS_ROOT}/${RUN_ID}/metrics/wandb}"
WANDB_PROJECT="${WANDB_PROJECT:-terminal_rl}"
WANDB_GROUP="${WANDB_GROUP:-qwen3-8b_seta_exploration_${VARIANT_ID}_${EPISODIC_TURN_TAG}}"
WANDB_KEY="${WANDB_KEY:-${WANDB_API_KEY:-}}"
if [[ -n "${WANDB_KEY}" && -z "${WANDB_API_KEY:-}" ]]; then
    WANDB_API_KEY="${WANDB_KEY}"
fi
RJOB_LOG_ROOT="${RJOB_LOG_ROOT:-${OPENCLAW_HOME}/runs/rjob_logs/terminal_rl_${VARIANT_ID}}"

RJOB_NAME="${RJOB_NAME:-a57-qbal-v0710}"
RJOB_MEMORY="${RJOB_MEMORY:-${DEFAULT_RJOB_MEMORY}}"
RJOB_CPU="${RJOB_CPU:-${DEFAULT_RJOB_CPU}}"
RJOB_GPU="${RJOB_GPU:-${NUM_GPUS}}"
